/** Titik tengah dan elipsis yang dipakai cap di luar ASCII. */
export const MIDDLE_DOT = '·';
export const ELLIPSIS = '…';

/** Glyph terurai: sembilan bilangan 5-bit per karakter (bit 4 = kolom paling kiri). */
const GLYPHS = new Map<string, readonly number[]>();
for (const [char, source] of Object.entries(SOURCE)) {
  const rows = source.split('/');
  GLYPHS.set(
    char,
    rows.map((row) => Number.parseInt(row.replaceAll('#', '1').replaceAll('.', '0'), 2)),
  );
}

/** Baris-baris glyph untuk `char`, atau `null` bila karakter tak punya glyph. */
export function glyphOf(char: string): readonly number[] | null {
  return GLYPHS.get(char) ?? null;
}

/** Karakter yang punya glyph (dipakai tes). */
export function glyphChars(): string[] {
  return [...GLYPHS.keys()];
}

/** Sumber mentah glyph (dipakai tes untuk memeriksa bentuk 5 x 9). */
export function glyphSource(): Readonly<Record<string, string>> {
  return SOURCE;
}
